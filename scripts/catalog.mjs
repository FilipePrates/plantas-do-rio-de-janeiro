import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import {
  parseCatalog,
  representedSpeciesCount,
  photoMatchesPlant,
  isProfile,
  inaturalistPhotoRights,
} from "../src/catalog.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = resolve(root, "src/data/plants.json");
const read = (path) => JSON.parse(readFileSync(path, "utf8"));
function verify(catalog, release = false) {
  catalog = parseCatalog(catalog);
  const thumbnailManifestPath = resolve(
    root,
    "src/data/plant-thumbnail-manifest.json",
  );
  const thumbnails = existsSync(thumbnailManifestPath)
    ? read(thumbnailManifestPath)
    : {};
  for (const plant of catalog.plants) {
    if (release && (plant.reviewStatus !== "reviewed" || (isProfile(plant) && !plant.photos.length)))
      throw new Error(
        `${plant.scientificName}: revise o texto e inclua uma foto antes do lançamento.`,
      );
    for (const photo of plant.photos) {
      if (!photoMatchesPlant(plant, photo.taxonName))
        console.warn(
          `Aviso: ${plant.scientificName}: o nome da foto ${photo.photoId} no iNaturalist (${photo.taxonName}) difere do nome da ficha; pode ser sinonímia ou uma diferença taxonômica.`,
        );
      const path = resolve(root, "assets/plants", photo.fileName);
      const digest = createHash("sha256")
        .update(readFileSync(path))
        .digest("hex");
      if (digest !== photo.sha256)
        throw new Error(`${photo.fileName}: hash divergente.`);
      const thumbnail = thumbnails[photo.fileName];
      if (thumbnail) {
        if (
          !/^inat-[0-9]+\.webp$/.test(thumbnail.fileName) ||
          thumbnail.sourceSha256 !== photo.sha256
        )
          throw new Error(`${photo.fileName}: origem da miniatura divergente.`);
        const thumbnailHash = createHash("sha256")
          .update(
            readFileSync(
              resolve(root, "assets/plants/thumbnails", thumbnail.fileName),
            ),
          )
          .digest("hex");
        if (thumbnailHash !== thumbnail.sha256)
          throw new Error(`${photo.fileName}: hash da miniatura divergente.`);
      }
      const evidence = read(
        resolve(root, `sources/inaturalist/photos/${photo.photoId}.json`),
      );
      if (
        evidence.photo.license_code !== photo.licenseCode ||
        evidence.photo.id !== photo.photoId ||
        evidence.observation.id !== photo.observationId ||
        evidence.observation.taxon.id !== photo.taxonId ||
        evidence.observation.taxon.name !== photo.taxonName ||
        evidence.download.sha256 !== photo.sha256 ||
        evidence.download.url !== photo.sourceUrl ||
        evidence.download.retrievedAt !== photo.downloadedAt ||
        evidence.creator !== photo.creator
      )
        throw new Error(
          `${photo.fileName}: a proveniência não coincide com a licença arquivada.`,
        );
      const rights = inaturalistPhotoRights(evidence.photo);
      for (const [key, value] of Object.entries(rights)) {
        if (photo[key] !== value) throw new Error(`${photo.fileName}: atribuição ou licença divergente (${key}).`);
      }
      if (release && photo.reviewStatus !== "reviewed")
        throw new Error(`${photo.fileName}: foto ainda não revisada.`);
    }
  }
  return catalog;
}
function generate(catalog) {
  execFileSync("python3", [resolve(root, "scripts/generate_thumbnails.py")], {
    stdio: "inherit",
  });
  const files = [
    ...new Set(
      catalog.plants.flatMap((p) => p.photos.map((photo) => photo.fileName)),
    ),
  ].sort();
  writeFileSync(
    resolve(root, "src/data/plant-images.ts"),
    '// Generated by npm run catalog:generate. Media rights: verified iNaturalist CC0 / CC BY.\nimport type { ImageSourcePropType } from "react-native";\nexport const plantImages: Record<string, ImageSourcePropType> = {\n' +
      files
        .map(
          (file) =>
            `  ${JSON.stringify(file)}: require(${JSON.stringify("../../assets/plants/" + file)}),`,
        )
        .join("\n") +
      "\n};\n",
  );
  console.log(
    `${catalog.plants.length} fichas; ${representedSpeciesCount(catalog)} espécies; ${files.length} fotos locais CC0 / CC BY.`,
  );
  const summary = {
    generatedAt: new Date().toISOString(),
    entries: catalog.plants.length,
    profiles: catalog.plants.filter(isProfile).length,
    checklistOnly: catalog.plants.filter((p) => !isProfile(p)).length,
    representedSpecies: representedSpeciesCount(catalog),
    families: new Set(catalog.plants.map((p) => p.family)).size,
    invasiveEntries: catalog.plants.filter((p) => p.origin === "invasive")
      .length,
    groupedGenera: catalog.plants
      .filter((p) => p.rank === "genus")
      .map((p) => ({
        genus: p.genus,
        nativeRioStateAtlanticForestSpecies: p.regionalSpecies.length,
        terrestrialSpecies: p.regionalSpecies.filter((s) =>
          s.substrates.includes("Terrícola"),
        ).length,
      })),
    cc0Photos: catalog.plants.flatMap((p) => p.photos).filter((p) => p.licenseCode === "cc0").length,
    ccByPhotos: catalog.plants.flatMap((p) => p.photos).filter((p) => p.licenseCode === "cc-by").length,
    illustratedEntries: catalog.plants.filter((p) => p.photos.length).length,
    missingPhotos: catalog.plants
      .filter((p) => isProfile(p) && !p.photos.length)
      .map((p) => ({ id: p.id, scientificName: p.scientificName })),
    draftEntries: catalog.plants.filter((p) => p.reviewStatus === "draft")
      .length,
    draftPhotos: catalog.plants
      .flatMap((p) => p.photos)
      .filter((p) => p.reviewStatus === "draft").length,
  };
  writeFileSync(
    resolve(root, "docs/catalog-status.json"),
    JSON.stringify(summary, null, 2) + "\n",
  );
}
const [command = "check", argument, flag] = process.argv.slice(2);
try {
  if (command === "import") {
    if (!argument)
      throw new Error(
        "Uso: npm run catalog:import -- /caminho/catalogo.json [--apply]",
      );
    const incoming = verify(read(resolve(argument)));
    console.log(
      `Importação validada: ${incoming.plants.length} fichas, ${representedSpeciesCount(incoming)} espécies.`,
    );
    if (flag !== "--apply") {
      console.log(
        "Prévia somente. Acrescente --apply para aplicar e gerar os índices.",
      );
    } else {
      mkdirSync(resolve(root, "backups"), { recursive: true });
      copyFileSync(
        catalogPath,
        resolve(root, `backups/catalog-${Date.now()}.json`),
      );
      const temp = catalogPath + ".tmp";
      writeFileSync(temp, JSON.stringify(incoming, null, 2) + "\n");
      renameSync(temp, catalogPath);
      generate(incoming);
    }
  } else {
    const catalog = verify(read(catalogPath), command === "release-check");
    if (command === "check" || command === "release-check")
      console.log(
        `Catálogo válido: ${catalog.plants.length} fichas / ${representedSpeciesCount(catalog)} espécies.`,
      );
    else if (command === "generate") generate(catalog);
    else if (command === "editor-sync") {
      const target = resolve(
        argument || resolve(root, "../plantas-rio-content-editor"),
      );
      if (
        target === root ||
        !existsSync(resolve(target, "package.json")) ||
        read(resolve(target, "package.json")).name !==
          "plantas-rio-content-editor"
      )
        throw new Error(
          "Escolha o repositório plantas-rio-content-editor; o editor de aves não pode ser usado.",
        );
      mkdirSync(resolve(target, "public/photos"), { recursive: true });
      copyFileSync(catalogPath, resolve(target, "public/catalog.json"));
      for (const file of ["catalog.mjs", "catalog.d.mts"])
        copyFileSync(resolve(root, "src", file), resolve(target, "src", file));
      for (const photo of catalog.plants.flatMap((p) => p.photos))
        copyFileSync(
          resolve(root, "assets/plants", photo.fileName),
          resolve(target, "public/photos", photo.fileName),
        );
      console.log(
        "Catálogo, contrato e fotos copiados para o editor de plantas.",
      );
    } else throw new Error("Comando desconhecido.");
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
